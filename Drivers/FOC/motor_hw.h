#ifndef MOTOR_HW_H
#define MOTOR_HW_H

#include <stdbool.h>

/*
*********************************************************************************************************
*   函数声明
*********************************************************************************************************
*/

/*
*********************************************************************************************************
*   函 数 名: MotorHw_Init
*   功能说明: 校准ADC并启动编码器DMA、双ADC注入采样和TIM3/TIM1计数
*   形    参: 无；须在CubeMX GPIO、DMA、SPI、ADC和TIM初始化之后调用一次
*   返 回 值: true表示外设均已启动；false表示至少一步失败，PWM始终保持关闭
*********************************************************************************************************
*/
bool MotorHw_Init(void);

/*
*********************************************************************************************************
*   函 数 名: MotorHw_StartPwm
*   功能说明: 以零占空比使能TIM1三相PWM输出
*   形    参: 无
*   返 回 值: true表示三个通道均成功启动；false表示已回退关闭全部通道
*********************************************************************************************************
*/
bool MotorHw_StartPwm(void);

/*
*********************************************************************************************************
*   函 数 名: MotorHw_StopPwm
*   功能说明: 关闭TIM1三相PWM，并将下一次启动的比较值预置为零
*   形    参: 无
*   返 回 值: 无
*********************************************************************************************************
*/
void MotorHw_StopPwm(void);

/*
*********************************************************************************************************
*   函 数 名: MotorHw_SetPhaseDuty
*   功能说明: 写入U/V/W三相PWM占空比，供SVPWM输出层调用
*   形    参: duty_u - U相占空比，归一化范围[0.0, 1.0]
*             duty_v - V相占空比，归一化范围[0.0, 1.0]
*             duty_w - W相占空比，归一化范围[0.0, 1.0]
*   返 回 值: 无；越界输入自动钳位，实际输出更新时刻由TIM1预装载决定
*********************************************************************************************************
*/
void MotorHw_SetPhaseDuty(float duty_u, float duty_v, float duty_w);

#endif /* MOTOR_HW_H */
